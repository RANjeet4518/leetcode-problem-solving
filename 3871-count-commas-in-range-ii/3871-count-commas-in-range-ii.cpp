class Solution {
public:
    long long countCommas(long long n) {
     long long mx=0;
     if(n>=999999){
        mx+=999999-999;
     }
     else if(n>999){
        mx+=n-999;
     }
     
     if(n>=999999999){
        mx+=(999999999-999999)*2;
     }
     else if(n>999999){
        mx+=(n-999999)*2;
     }
     if(n>=999999999999){
        mx+=(999999999999-999999999)*3;
     }
     else if(n>999999999){
        mx+=(n-999999999)*3;
     }
      if(n>=999999999999999){
        mx+=(999999999999999-999999999999)*4;
     }
     else if(n>999999999999){
        mx+=(n-999999999999)*4;
     }
     if(n==1000000000000000){
        mx+=5;
     }
     
     
     return mx;
        
    }
};